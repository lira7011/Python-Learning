for n in range(1, 101): #para um numero em um intervalo de 1 a 100:
    for m in range(1, 11): #e para um outro numero em o intervalo de 1 a 10:
        resultado = n * m #crie uma variavel resultado que multiplica tanto o n quanto m
        print(f'{n} x {m} = {resultado}') #exibe a tabuada de 1 a 100 de forma visivelmente melhor com 'x' e '='
